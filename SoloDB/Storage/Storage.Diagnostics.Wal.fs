namespace SoloDatabase

open System.Runtime.InteropServices

module internal StorageCoordinationWal =
    let run (check: StorageCoordinationChecks) firstMain secondMain =
        check.Run(fun () ->
            let first = check.Open("Open first WAL session", firstMain)
            let second = check.Open("Open second WAL session", secondMain)
            check.Require("WAL capability", "Both sessions must support shared memory for Wal diagnostics.", fun () -> first.HasSharedMemory && second.HasSharedMemory)
            check.Code("First WAL pager reader", 0, fun () -> first.Lock(1))
            check.Code("Second WAL pager reader", 0, fun () -> second.Lock(1))
            let firstAddress = check.Map("Extend first WAL region", first, 0, 2)
            let secondAddress = check.Map("Map peer WAL region", second, 0, 0)
            check.Call("Write first WAL test pattern", System.Nullable<int>(), fun () -> Marshal.WriteInt32(firstAddress, 173))
            check.Call("First WAL barrier", System.Nullable<int>(), first.SharedMemoryBarrier)
            check.Call("Peer WAL barrier", System.Nullable<int>(), second.SharedMemoryBarrier)
            check.Require("Shared WAL bytes", "The second session cannot see the first session's mapped bytes.", fun () -> Marshal.ReadInt32(secondAddress) = 173)
            let nextAddress = check.Map("Extend second WAL region", first, 1, 2)
            check.Call("Write second WAL test pattern", System.Nullable<int>(), fun () -> Marshal.WriteInt32(nextAddress, 941))
            check.Call("Region growth barrier", System.Nullable<int>(), first.SharedMemoryBarrier)
            let nextPeer = check.Map("Map peer second WAL region", second, 1, 0)
            check.Call("Peer region growth barrier", System.Nullable<int>(), second.SharedMemoryBarrier)
            check.Require("Distinct WAL regions", "Different WAL regions share one address.", fun () -> firstAddress <> nextAddress && secondAddress <> nextPeer)
            check.Require("Second-region WAL bytes", "The peer cannot see the extended WAL region's bytes.", fun () -> Marshal.ReadInt32(nextPeer) = 941)
            let retained = check.Map("Remap first WAL region after growth", first, 0, 0)
            check.Require("Stable WAL region address", "A mapped region moved while its session was live.", fun () -> retained = firstAddress)
            for slot = 0 to 7 do
                check.Slot($"First shared WAL slot {slot}", first, slot, 1, 6, 0)
                check.Slot($"Peer shared WAL slot {slot}", second, slot, 1, 6, 0)
                check.Slot($"Release first shared WAL slot {slot}", first, slot, 1, 5, 0)
                check.Slot($"Shared peer bars exclusive WAL slot {slot}", first, slot, 1, 10, 5)
                check.Slot($"Release peer shared WAL slot {slot}", second, slot, 1, 5, 0)
                check.Slot($"First exclusive WAL slot {slot}", first, slot, 1, 10, 0)
                check.Slot($"Exclusive bars shared WAL slot {slot}", second, slot, 1, 6, 5)
                check.Slot($"Exclusive bars exclusive WAL slot {slot}", second, slot, 1, 10, 5)
                check.Slot($"Release exclusive WAL slot {slot}", first, slot, 1, 9, 0)
            check.Slot("Exclusive WAL slot range", first, 1, 7, 10, 0)
            check.Slot("Range bars its final WAL slot", second, 7, 1, 6, 5)
            check.Slot("Disjoint WAL slot remains usable", second, 0, 1, 10, 0)
            check.Slot("Release disjoint WAL slot", second, 0, 1, 9, 0)
            check.Unmap("Unmap first WAL session", first, 0)
            let surviving = check.Map("Remap peer after first unmaps", second, 0, 0)
            check.Require("Peer address survives unmap", "Unmapping another session moved the peer's live region.", fun () -> surviving = secondAddress)
            check.Require("Peer bytes survive unmap", "Unmapping another session discarded the peer's mapped bytes.", fun () -> Marshal.ReadInt32(surviving) = 173)
            check.Close("Close first WAL session", first)
            check.Slot("Peer acquires closed session's WAL range", second, 1, 7, 10, 0)
            let afterClose = check.Map("Remap peer after first closes", second, 0, 0)
            check.Require("Peer address survives close", "Closing another session moved the peer's live region.", fun () -> afterClose = secondAddress)
            check.Require("Peer bytes survive close", "Closing another session discarded the peer's mapped bytes.", fun () -> Marshal.ReadInt32(afterClose) = 173)
            check.Slot("Release surviving WAL range", second, 1, 7, 9, 0)
            check.Unmap("Unmap surviving WAL session", second, 1))
